CREATE SCHEMA IF NOT EXISTS demo;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
REVOKE ALL ON SCHEMA demo FROM PUBLIC;
CREATE ROLE analyst LOGIN PASSWORD 'analyst_local_only' NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
ALTER ROLE analyst SET default_transaction_read_only = on;
ALTER ROLE analyst SET statement_timeout = '5s';
ALTER ROLE analyst SET search_path = pg_catalog, demo;
GRANT CONNECT ON DATABASE analytics TO analyst;
REVOKE TEMPORARY ON DATABASE analytics FROM PUBLIC;
CREATE TABLE demo.customers (id integer PRIMARY KEY, region text NOT NULL, age_group text NOT NULL, registered_at date NOT NULL, tier text NOT NULL);
CREATE TABLE demo.products (id integer PRIMARY KEY, name text NOT NULL, category text NOT NULL, price numeric(12,2) NOT NULL, cost numeric(12,2) NOT NULL);
CREATE TABLE demo.orders (id integer PRIMARY KEY, customer_id integer NOT NULL REFERENCES demo.customers, ordered_at date NOT NULL, status text NOT NULL, channel text NOT NULL);
CREATE TABLE demo.order_items (id integer PRIMARY KEY, order_id integer NOT NULL REFERENCES demo.orders, product_id integer NOT NULL REFERENCES demo.products, quantity integer NOT NULL, unit_price numeric(12,2) NOT NULL);
CREATE TABLE demo.campaigns (id integer PRIMARY KEY, name text NOT NULL, start_date date NOT NULL, end_date date NOT NULL, discount_rate numeric(4,2) NOT NULL, category text NOT NULL);
CREATE INDEX ON demo.orders (ordered_at, status);
CREATE INDEX ON demo.orders (customer_id);
CREATE INDEX ON demo.order_items (order_id);
CREATE INDEX ON demo.order_items (product_id);
GRANT USAGE ON SCHEMA demo TO analyst;
GRANT SELECT ON ALL TABLES IN SCHEMA demo TO analyst;
